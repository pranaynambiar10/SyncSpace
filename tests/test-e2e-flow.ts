import { createClient } from '@supabase/supabase-js';
import * as dotenv from 'dotenv';
import * as path from 'path';
import WebSocket from 'ws';

(global as any).WebSocket = WebSocket;

dotenv.config({ path: path.resolve(process.cwd(), '.env.local') });

const supabaseUrl = process.env.VITE_SUPABASE_URL || '';
const supabaseAnonKey = process.env.VITE_SUPABASE_ANON_KEY || '';

const supabase = createClient(supabaseUrl, supabaseAnonKey, {
  auth: { persistSession: false }
});

async function runE2ETest() {
  console.log('====================================================');
  console.log('SyncSpace Campus — End-to-End Automated Verification');
  console.log('====================================================\n');

  const testEmail = `cusat.student.${Date.now()}@ug.cusat.ac.in`;
  const testPassword = 'Password@123';
  const fullName = 'Shafeeq Rahman';

  console.log(`[Step 1] Registering CUSAT student: ${testEmail}...`);
  const { data: authData, error: authError } = await supabase.auth.signUp({
    email: testEmail,
    password: testPassword,
    options: {
      data: {
        full_name: fullName
      }
    }
  });

  if (authError) {
    console.error('❌ Sign up failed:', authError.message);
    return;
  }

  const user = authData.user;
  console.log('✅ User registered successfully. User ID:', user?.id);

  // If session is returned (or confirmation not strictly enforced)
  let userClient = supabase;
  if (authData.session) {
    console.log('✅ Active session received. Creating authenticated client.');
    userClient = createClient(supabaseUrl, supabaseAnonKey, {
      auth: { persistSession: false },
      global: {
        headers: {
          Authorization: `Bearer ${authData.session.access_token}`
        }
      }
    });
  } else {
    console.log('ℹ️ Email confirmation may be required by Supabase auth settings.');
    console.log('Trying sign in...');
    const { data: signInData, error: signInError } = await supabase.auth.signInWithPassword({
      email: testEmail,
      password: testPassword
    });

    if (signInError) {
      console.log('ℹ️ Sign in with password note:', signInError.message);
      console.log('Note: If "Email not confirmed", toggle "Enable Email Confirmations = OFF" in Supabase Auth settings to test instant login.');
    } else if (signInData.session) {
      console.log('✅ Signed in successfully!');
      userClient = createClient(supabaseUrl, supabaseAnonKey, {
        auth: { persistSession: false },
        global: {
          headers: {
            Authorization: `Bearer ${signInData.session.access_token}`
          }
        }
      });
    }
  }

  console.log('\n[Step 2] Checking Profile creation & CUSAT student verification...');
  if (user?.id) {
    const { data: profile, error: pErr } = await userClient
      .from('profiles')
      .select('id, full_name, email, verified_student')
      .eq('id', user.id)
      .maybeSingle();

    if (pErr) {
      console.log('❌ Profile lookup error:', pErr.message);
    } else if (profile) {
      console.log('✅ Profile record automatically generated by auth trigger:');
      console.log(`   - Name: ${profile.full_name}`);
      console.log(`   - Verified Student: ${profile.verified_student} (CUSAT institutional domain)`);
    } else {
      console.log('ℹ️ Profile row not yet accessible or awaiting auth trigger execution.');
    }
  }

  console.log('\n[Step 3] Checking Academic Notes Library subjects & modules...');
  const { data: subjects, error: sErr } = await userClient
    .from('subjects')
    .select('id, name, code, subject_modules(id, module_number, title)');

  if (sErr) {
    console.log('❌ Subjects query:', sErr.message);
  } else {
    console.log(`✅ Retrieved ${subjects?.length || 0} subjects from CUSAT catalog:`);
    subjects?.forEach(s => {
      console.log(`   - ${s.code}: ${s.name} (${(s.subject_modules as any[])?.length || 0} syllabus modules)`);
    });
  }

  console.log('\n[Step 4] Querying Top Rated Notes Discovery View...');
  const { data: topNotes, error: tErr } = await userClient
    .from('top_rated_notes_view')
    .select('*')
    .limit(5);

  if (tErr) {
    console.log('❌ Top notes view query:', tErr.message);
  } else {
    console.log(`✅ Top rated notes view active. Returned count: ${topNotes?.length || 0}`);
  }

  console.log('\n[Step 5] Checking Storage Buckets...');
  const { data: buckets, error: bErr } = await userClient.storage.listBuckets();
  if (bErr) {
    console.log('❌ Storage buckets query:', bErr.message);
  } else {
    console.log('✅ Storage buckets:', buckets?.map(b => `${b.name} (${b.public ? 'public' : 'private'})`));
  }

  console.log('\n====================================================');
  console.log('End-to-End Test Completed Successfully');
  console.log('====================================================');
}

runE2ETest();
